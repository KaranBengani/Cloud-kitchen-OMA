export type Language = 'en' | 'hi';
export type TranslationKey = Key;
type Vars = Record<string, string | number>;
type I18n = {
  language: Language;
  locale: string; // for dates: 'en-IN' or 'hi-IN' (both use 0-9 digits, which read faster for prices)
  setLanguage: (l: Language) => void;
  t: (key: Key, vars?: Vars) => string;
};

const dictionaries: Record<Language, Record<Key, string>> = { en, hi };
const STORAGE_KEY = 'language';
const I18nContext = createContext<I18n | null>(null);

function format(template: string, vars?: Vars): string {
  return vars ? template.replace(/\{(\w+)\}/g, (match, name: string) => String(vars[name] ?? match)) : template;
}

export function I18nProvider({ children }: { children: ReactNode }) {
  // First launch follows the phone's language; after that the user's choice is remembered per phone.
  const [language, setLanguageState] = useState<Language>(
    getLocales()[0]?.languageCode === 'hi' ? 'hi' : 'en',
  );

  useEffect(() => {
    SecureStore.getItemAsync(STORAGE_KEY).then((saved) => {
      if (saved === 'en' || saved === 'hi') setLanguageState(saved);
    });
  }, []);

  const setLanguage = (l: Language) => {
    setLanguageState(l);
    SecureStore.setItemAsync(STORAGE_KEY, l);
  };

  return (
    <I18nContext
      value={{
        language,
        locale: language === 'hi' ? 'hi-IN' : 'en-IN',
        setLanguage,
        t: (key, vars) => format(dictionaries[language][key], vars),
      }}
    >
      {children}
    </I18nContext>
  );
}

export function useI18n(): I18n {
  const ctx = use(I18nContext);
  if (!ctx) throw new Error('useI18n must be used inside I18nProvider');
  return ctx;
}
